def main():

    text = FILE.read_text(
        encoding="utf-8"
    )

    count = 0

    for old, new in REPLACEMENTS.items():

        if old in text:
            text = text.replace(old, new)
            count += 1


    FILE.write_text(
        text,
        encoding="utf-8"
    )

    print("Готово")
    print("Заменено:", count)
    print(FILE)


if __name__ == "__main__":
    main()