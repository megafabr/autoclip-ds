def main():

    if not FILE.exists():
        print("Файл не найден:")
        print(FILE)
        return


    text = FILE.read_text(
        encoding="utf-8"
    )

    replaced = 0

    for old, new in REPLACEMENTS.items():

        if old in text:
            text = text.replace(old, new)
            replaced += 1


    FILE.write_text(
        text,
        encoding="utf-8"
    )


    print("Готово")
    print("Заменено:", replaced)
    print(FILE)


if __name__ == "__main__":
    main()